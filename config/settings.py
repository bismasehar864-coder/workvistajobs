# =========================================================
# EMAIL
# =========================================================
#
# Credentials come from the environment and are never committed. With
# neither set - the default for a fresh checkout - everything falls
# back to the console backend, so digests print to the terminal and
# nothing is actually sent. Export both and it starts sending, with no
# code change.
#
#   export WORKVISTA_EMAIL_USER=you@gmail.com
#   export WORKVISTA_EMAIL_PASSWORD=<16-char app password>
#
# Gmail needs an APP PASSWORD, not the account password: Google
# withdrew password SMTP for third-party apps in May 2022. Generate one
# at myaccount.google.com/apppasswords with 2-Step Verification on.

EMAIL_HOST_USER = env("WORKVISTA_EMAIL_USER", "")

# Google displays an App Password as four groups of four ("abcd efgh
# ijkl mnop") but SMTP wants the sixteen characters with no spaces.
# Stripping here means either form works in .env.
EMAIL_HOST_PASSWORD = env("WORKVISTA_EMAIL_PASSWORD", "").replace(" ", "")

if EMAIL_HOST_USER and EMAIL_HOST_PASSWORD:
    EMAIL_BACKEND = "django.core.mail.backends.smtp.EmailBackend"
    EMAIL_HOST = env("WORKVISTA_EMAIL_HOST", "smtp.gmail.com")
    EMAIL_PORT = int(env("WORKVISTA_EMAIL_PORT", "587"))
    EMAIL_USE_TLS = True
    # Don't let a hung mail server hold a management command open
    # forever; send_pending_digests catches the timeout per user and
    # simply retries that one on the next run.
    EMAIL_TIMEOUT = int(env("WORKVISTA_EMAIL_TIMEOUT", "20"))
else:
    EMAIL_BACKEND = "django.core.mail.backends.console.EmailBackend"

