def env(key, default=None, required=False):
    """One environment variable, with a useful error when it's missing.

    Failing at startup naming the variable beats failing later with a
    MySQL access-denied error that says nothing about which knob to
    turn.
    """

    value = os.environ.get(key, default)

    if required and not value:
        raise ImproperlyConfigured(
            f"{key} is not set. Copy .env.example to .env and fill it in - "
            f"see guidebook/02-setup-and-running.md."
        )

    return value


def env_bool(key, default=False):
    return str(env(key, str(default))).strip().lower() in ("1", "true", "yes", "on")


def env_list(key, default=""):
    return [item.strip() for item in str(env(key, default)).split(",") if item.strip()]


